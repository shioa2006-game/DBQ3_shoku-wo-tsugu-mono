// 描画済みアイコンをRGBAで返す。
export function renderIcon(id) {
  const draw = ICONS[id];
  if (!draw) throw Error(`No icon art for ${id}`);
  const ic = new PixelIcon();
  draw(ic);
  ic.outline(OUTLINE);
  return ic;
}
