// 16行×16文字の全面ドット絵。
function art(rows) {
  if (rows.length !== ICON_SIZE || rows.some((r) => r.length !== ICON_SIZE)) {
    throw Error(`Icon art must be ${ICON_SIZE}x${ICON_SIZE}: ${rows.map((r) => r.length).join(',')}`);
  }
  return (ic) => ic.grid(rows, PALETTE);
}

const C = PALETTE;

// 別のアイコンを素材違いの色で描く（銅の金具→鉄の金具など）。map: { 元の色: 新しい色 }
function recolor(id, map) {
  return (ic) => {
    const src = new PixelIcon();
    ICONS[id](src);
    for (let y = 0; y < ICON_SIZE; y += 1) {
      for (let x = 0; x < ICON_SIZE; x += 1) {
        const i = (y * ICON_SIZE + x) * 4;
        if (!src.data[i + 3]) continue;
        const hex = '#' + [0, 1, 2].map((k) => src.data[i + k].toString(16).padStart(2, '0')).join('');
        ic.px(x, y, map[hex] ?? hex);
      }
    }
  };
}

